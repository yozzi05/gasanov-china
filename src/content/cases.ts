// ─────────────────────────────────────────────────────────────────────────────
// КЕЙСЫ: карточки-накладные, всплывающее окно и отзывы.
// Исходники каждого кейса - assets/cases/<id>/ (case.md и медиа).
// Медиа на сайт попадают командой `npm run images` (public/cases/<id>/).
//
// Поля, которых нет (пустая строка, пустой список, нет ключа), на сайте не выводятся.
// media.src:
//   • video - путь к файлу от корня сайта: "/cases/g17-001/video.mp4";
//   • photo, chat - имя картинки из манифеста: "cases/g17-007/photo-1".
// ─────────────────────────────────────────────────────────────────────────────

export type CaseMedia = {
  type: "video" | "photo" | "chat";
  src: string;
  /** у видео - картинка-обложка (имя из манифеста) */
  poster?: string;
  /** у видео - субтитры, путь от корня сайта */
  captions?: string;
  /** подпись под кадром */
  caption?: string;
  /** у видео - без звука: muted, без кнопки звука */
  muted?: boolean;
};

export type CaseFacts = {
  weight?: string;
  days?: string;
  tariff?: string;
  goods?: string;
  route?: string;
};

/** Карточка в блоке «Отзывы»: цитата или скриншот переписки */
export type CaseReview = { type: "quote"; text: string } | { type: "shot"; src: string; alt: string };

export type CaseItem = {
  id: string;
  /** заголовок: на карточке и в окне */
  title: string;
  /** строка «Отметка» на карточке */
  meta: string;
  /** обложка карточки-накладной (имя из манифеста: public/images или cases/<id>/…).
   *  Обложка видео в окне - отдельно, media[].poster */
  cover: string;
  tags: string[];
  task: string;
  done: string;
  /** заголовок блока «Что сделали», если в case.md он другой */
  doneTitle?: string;
  result: string;
  /** цитата клиента в окне */
  quote?: string;
  transcript?: string;
  facts: CaseFacts;
  media: CaseMedia[];
  /** карточки в блоке «Отзывы» */
  reviews: CaseReview[];
};

const v = (id: string, caption?: string, captions = true): CaseMedia => ({
  type: "video",
  src: `/cases/${id}/video.mp4`,
  poster: `cases/${id}/poster`,
  ...(captions ? { captions: `/cases/${id}/captions.vtt` } : {}),
  ...(caption ? { caption } : {}),
});

